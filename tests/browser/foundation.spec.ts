import { expect, test } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
test('registration, onboarding, workspaces, themes, mobile navigation and platform', async ({ page }) => {
    const errors: string[] = [];
    page.on('pageerror', (e) => errors.push(e.message));
    const email = `browser-${Date.now()}@example.test`;
    const password = randomBytes(24).toString('hex');
    const code = `$o=App\\Models\\Organisation::create(['name'=>'Browser Demo · Acorn Studio']);echo app(App\\Services\\MembershipService::class)->invite($o,${JSON.stringify(email)},'owner');`;
    const invite = new URL(execFileSync('php', ['artisan', 'tinker', '--execute=' + code], { encoding: 'utf8' }).trim()).pathname;
    await page.goto(invite);
    await page.getByLabel('Name', { exact: true }).fill('Browser Demonstration');
    await expect(page.getByLabel('Email address', { exact: true })).toHaveValue(email);
    await page.getByLabel('Password', { exact: true }).fill(password);
    await page.getByLabel('Confirm password', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Create account' }).click();
    await expect(page).toHaveURL(/verify-email/);
    execFileSync('php', ['artisan', 'development:verify', email]);
    await page.goto(invite);
    await page.getByRole('button', { name: 'Accept invitation' }).click();
    await expect(page.getByRole('heading', { name: 'Workspace overview' })).toBeVisible();
    await expect(page.getByText('No campaigns yet. Prepare your audience, identity and email content to begin.')).toBeVisible();
    await page.screenshot({ path: 'test-results/dashboard-light.png', fullPage: true, animations: 'disabled' });
    await page.getByRole('button', { name: 'Toggle theme' }).click();
    await page.getByRole('menuitem', { name: 'Dark', exact: true }).click();
    await expect(page.locator('html')).toHaveClass(/dark/);
    await page.reload();
    await expect(page.locator('html')).toHaveClass(/dark/);
    await page.screenshot({ path: 'test-results/dashboard-dark.png', fullPage: true, animations: 'disabled' });
    execFileSync('php', ['artisan', 'platform:promote', email]);
    await page.goto('/organisations');
    await page.getByLabel('Organisation name', { exact: true }).fill('Browser Demo · Second workspace');
    await page.getByRole('button', { name: 'Create organisation', exact: true }).click();
    await expect(page.getByText(/Browser Demo · Second workspace · owner/)).toBeVisible();
    const workspace = page.getByLabel('WORKSPACE', { exact: true });
    const options = await workspace.locator('option').allTextContents();
    expect(options).toContain('Browser Demo · Acorn Studio');
    await workspace.selectOption({ label: 'Browser Demo · Acorn Studio' });
    await expect(page.getByText(/Browser Demo · Acorn Studio · owner/)).toBeVisible();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Toggle Sidebar' }).click();
    await expect(page.getByRole('link', { name: 'Organisations', exact: true })).toBeVisible();
    await page.screenshot({ path: 'test-results/mobile-navigation.png', fullPage: true, animations: 'disabled' });
    await page.keyboard.press('Escape');
    await page.screenshot({ path: 'test-results/dashboard-mobile.png', fullPage: true, animations: 'disabled' });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
    await page.setViewportSize({ width: 1440, height: 1000 });
    execFileSync('php', ['artisan', 'platform:promote', email]);
    await page.goto('/platform');
    await expect(page.getByRole('heading', { name: 'Platform administration' })).toBeVisible();
    await page.getByRole('link', { name: 'Queue monitor' }).click();
    await expect(page).toHaveURL(/horizon/);
    expect(errors).toEqual([]);
});
